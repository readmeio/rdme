#! /usr/bin/env node

// @ts-check
// oxlint-disable no-console -- This script reports a stale or missing generated declaration.

/**
 * `ReadmeApiPaths` is the literal type of the OpenAPI paths we derive types from.
 * Printing that type is most of `tsc`, so it is checked in and only regenerated here.
 */

import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const sourcePath = path.join(root, 'src/lib/types/openapiDoc.ts');
const outputPath = path.join(root, 'src/lib/types/openapiPaths.d.ts');
const sourceLabel = 'src/lib/types/openapiDoc.ts';

function sourceHash() {
  return createHash('sha256').update(fs.readFileSync(sourcePath)).digest('hex');
}

/**
 * @param {string} declaration
 */
function extractReadmeApiPaths(declaration) {
  const marker = 'declare const paths: ';
  const start = declaration.indexOf(marker);
  if (start === -1) {
    throw new Error('Generated declaration has no `declare const paths`.');
  }

  const braceStart = declaration.indexOf('{', start);
  let depth = 0;
  let end = -1;
  for (let i = braceStart; i < declaration.length; i += 1) {
    const char = declaration[i];
    if (char === '{') depth += 1;
    else if (char === '}') {
      depth -= 1;
      if (depth === 0) {
        end = i + 1;
        break;
      }
    }
  }
  if (end === -1) throw new Error('Could not find the end of the paths type.');

  return `export type ReadmeApiPaths = ${declaration.slice(braceStart, end)};\n`;
}

function stampHeader() {
  return `/**
 * Generated by \`npm run build:openapi-types\` from \`${sourceLabel}\`.
 * Do not edit. source-sha256: ${sourceHash()}
 */
`;
}

function writePaths() {
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'rdme-openapi-paths-'));
  try {
    const source = fs.readFileSync(sourcePath, 'utf8');
    const exportLine = 'export const readmeApiPaths = paths as unknown as ReadmeApiPaths;';
    if (!source.includes(exportLine)) {
      throw new Error(`Expected \`${exportLine}\` in ${sourceLabel}.`);
    }

    // Compile a copy that exports the inferred literal. The checked-in source asserts
    // to the generated alias so ordinary `tsc` does not serialize it.
    const patched = source
      .replace("import type { ReadmeApiPaths } from './openapiPaths.js';\n", '')
      .replace(exportLine, 'export type ReadmeApiPaths = typeof paths;');

    fs.writeFileSync(path.join(tmp, 'openapiDoc.ts'), patched);
    fs.writeFileSync(
      path.join(tmp, 'tsconfig.json'),
      JSON.stringify(
        {
          compilerOptions: {
            declaration: true,
            emitDeclarationOnly: true,
            erasableSyntaxOnly: true,
            module: 'node20',
            outDir: path.join(tmp, 'dist'),
            rootDir: tmp,
            skipLibCheck: true,
            strict: true,
            verbatimModuleSyntax: true,
          },
          files: [path.join(tmp, 'openapiDoc.ts')],
        },
        null,
        2,
      ),
    );

    // Resolve `oas/types` from this repo. A temp dir outside the project cannot.
    const nodeModulesLink = path.join(tmp, 'node_modules');
    fs.symlinkSync(path.join(root, 'node_modules'), nodeModulesLink);
    fs.writeFileSync(path.join(tmp, 'package.json'), JSON.stringify({ type: 'module' }));

    const tsc = spawnSync(
      path.join(root, 'node_modules/.bin/tsc'),
      ['-p', path.join(tmp, 'tsconfig.json'), '--pretty', 'false'],
      {
        stdio: 'inherit',
      },
    );
    if (tsc.status !== 0) process.exit(tsc.status ?? 1);

    const declaration = fs.readFileSync(path.join(tmp, 'dist/openapiDoc.d.ts'), 'utf8');
    fs.writeFileSync(outputPath, `${stampHeader()}${extractReadmeApiPaths(declaration)}`);
  } finally {
    fs.rmSync(tmp, { recursive: true, force: true });
  }
}

function copyPaths() {
  const destinationDir = path.join(root, 'dist/lib/types');
  fs.mkdirSync(destinationDir, { recursive: true });
  fs.copyFileSync(outputPath, path.join(destinationDir, 'openapiPaths.d.ts'));
}

function checkPaths() {
  if (!fs.existsSync(outputPath)) {
    console.error(`${path.relative(root, outputPath)} is missing. Run npm run build:openapi-types.`);
    process.exit(1);
  }

  const stamped = fs.readFileSync(outputPath, 'utf8').match(/source-sha256: ([a-f0-9]+)/);
  const actual = sourceHash();
  if (!stamped || stamped[1] !== actual) {
    console.error(`${path.relative(root, outputPath)} does not match ${sourceLabel}. Run npm run build:openapi-types.`);
    process.exit(1);
  }
}

const command = process.argv[2];
if (command === 'write') writePaths();
else if (command === 'check') checkPaths();
else if (command === 'copy') copyPaths();
else {
  console.error('Usage: node bin/openapi-paths.js <check|write|copy>');
  process.exit(1);
}
